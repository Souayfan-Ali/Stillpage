/** Unrelated, fictitious publisher sites (no list carries exceptions for them). */
const PUBLISHERS = [
  'https://www.daily-news-site.com',
  'https://blog.recipes-world.net',
  'https://forum.gamers-hub.org',
  'https://shop.store-front.co.uk',
];

function rows(endpoints: readonly Endpoint[], kind: string): DnrCase[] {
  return endpoints.flatMap(([url, type]) =>
    PUBLISHERS.map((initiator) => ({ url, type, initiator, expect: 'stop' as const, because: `${kind}: ${new URL(url).hostname}` })),
  );
}

export const MUST_BLOCK: readonly DnrCase[] = [...rows(ADS, 'ad endpoint'), ...rows(TRACKERS, 'tracker endpoint')];
