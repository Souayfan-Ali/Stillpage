/**
 * Scriptlet code files (P1-29, cosmetic notes §6.2): per pack and world, the referenced uBO functions once
 * (transitive closure, de-duplicated) plus a fixed dispatcher. Nothing in the file is built from list
 * data: arguments live in the shard data files as JSON and are passed as call arguments. The
 * dispatcher reads only its own pack's shards, looks the frame's host and parents up, and calls each
 * invocation inside `try/catch`. It never touches the network or storage. Hardened by P1-37
 * (`dispatcher.ts`); the protocol is `src/core/content/shard-data.ts`.
 */
import { minifySync } from 'rolldown/utils';
import type { ScriptWorld } from '../../src/core/catalog/registrations.js';
import { SHARD_DATA_VERSION, SHARD_QUEUE } from '../../src/core/content/shard-data.js';
import { closure, type Library, type ScriptletDef } from './library.js';
import { DISPATCHER_HEAD, dispatcherSource } from './dispatcher.js';

/** Longest scriptlet argument the dispatcher passes on (uBO's longest in the pinned lists is far below). */
const MAX_ARG_LENGTH = 65_536;

const NOTICE = (commit: string): string => `/*
 * Scriptlets from uBlock Origin (https://github.com/gorhill/uBlock), commit ${commit}.
 * Copyright (C) 2014-present Raymond Hill. GPL-3.0-or-later; see LICENSE and CREDITS.md.
 * Generated by the build: the functions below are uBO's, unchanged; the dispatcher is ours.
 */
`;

/**
 * Whitespace and comments only (store notes: minify, never obfuscate): no renaming, no compression, so
 * the shipped functions are uBO's text minus layout and the notice above them stays exact.
 */
function minified(code: string): string {
  const out = minifySync('scriptlets.js', code, { mangle: false, compress: false });
  if (out.errors.length > 0) throw new Error(`scriptlet code does not minify: ${out.errors.map((e) => e.message).join('; ')}`);
  return out.code;
}

/**
 * Our dispatcher, minified on its own with local names shortened (it is our code; uBO's functions keep
 * their names). Its free names — the captured natives, `KEY`, `PACK`, `fns` … — are left alone.
 */
const dispatcherCode = (world: ScriptWorld): string => {
  const out = minifySync('dispatcher.js', dispatcherSource(world), { mangle: true, compress: true });
  if (out.errors.length > 0) throw new Error(`dispatcher does not minify: ${out.errors.map((e) => e.message).join('; ')}`);
  return out.code;
};

export interface CodeFile {
  readonly text: string;
  /** Scriptlet name → index in `fns`. */
  readonly index: ReadonlyMap<string, number>;
}

/** The code file of one pack and world for `defs` (sorted by name: the index is stable for a build). */
export function bundle(lib: Library, pack: string, world: ScriptWorld, defs: readonly ScriptletDef[], commit: string): CodeFile {
  const sorted = [...new Map(defs.map((d) => [d.name, d])).values()].sort((a, b) => (a.name < b.name ? -1 : 1));
  const functions = closure(lib, sorted).map((f) => lib.functions.get(f) ?? '');
  const head = [
    DISPATCHER_HEAD,
    `const KEY = ${JSON.stringify(SHARD_QUEUE[world])};`,
    `const VERSION = ${JSON.stringify(SHARD_DATA_VERSION)};`,
    `const PACK = ${JSON.stringify(pack)};`,
    `const MAX_ARG = ${JSON.stringify(MAX_ARG_LENGTH)};`,
    'const scriptletGlobals = {};',
  ];
  const body = ['(function () {', "'use strict';", ...head, ...functions, `const fns = [${sorted.map((d) => d.fn).join(', ')}];`, dispatcherCode(world), '})();', ''].join('\n');
  return { text: `${NOTICE(commit)}${minified(body)}`, index: new Map(sorted.map((d, i) => [d.name, i])) };
}
