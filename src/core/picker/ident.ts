/**
 * CSS identifiers, attribute values and the "generated class name" heuristic for the selector
 * candidate generator (P2-17, cosmetic notes §9). Output must pass `core/sanitise`, which refuses letter
 * and digit escapes, so a token that would need one (`1col`, `-2x`) is refused here instead of
 * escaped. Pure and dependency-free: the picker content script imports it.
 */

/** Longest class, id or attribute value the generator will use; longer ones are rarely stable. */
const MAX_TOKEN_LENGTH = 200;
/** A segment shorter than this is never called generated (`h1`, `mt-4`, `col-md-6`). */
const HASH_MIN_SEGMENT = 5;
/** Share of character-class switches (lower / upper / digit) above which a segment looks generated. */
const HASH_SWITCH_RATIO = 0.5;
/** CSS-in-JS prefixes followed by a generated suffix (`css-1x2y3z`, `sc-bdVaJa`, `jsx-123`). */
const GENERATED_PREFIX = /^(?:css|sc|jsx|emotion|styled|svelte)-[A-Za-z0-9]{4,}$/;

/** Whitespace, controls and the characters the sanitiser denies even when escaped or quoted. */
const UNSAFE = /[\s\u0000-\u001f\u007f<{}]/;
/** Punctuation that must be escaped in an identifier (all of ASCII punctuation but `-` and `_`). */
const PUNCTUATION = /[!-,./:-@[-^`{-~]/g;
/** Inside a quoted value spaces are fine; controls and what the sanitiser denies anywhere are not. */
const UNSAFE_IN_STRING = /[\u0000-\u001f\u007f<{}]|url\(|\/\*/i;

/** `token` as a CSS identifier (`md:flex` → `md\:flex`), or `null` when it cannot be written safely. */
export function cssIdent(token: string): string | null {
  if (token === '' || token.length > MAX_TOKEN_LENGTH || UNSAFE.test(token)) return null;
  // A leading digit, or `-` + digit, needs a digit escape; a lone `-` / `--` is not a usable class.
  if (/^-?\d/.test(token) || token === '-' || token === '--') return null;
  return token.replace(PUNCTUATION, (ch) => `\\${ch}`);
}

/** `value` as a double-quoted CSS string, or `null` when empty, too long or unsafe. */
export function cssAttributeValue(value: string): string | null {
  if (value === '' || value.length > MAX_TOKEN_LENGTH || UNSAFE_IN_STRING.test(value)) return null;
  return `"${value.replace(/["\\]/g, (ch) => `\\${ch}`)}"`;
}

const charClass = (ch: string): number => (/\d/.test(ch) ? 0 : /[A-Z]/.test(ch) ? 1 : 2);

/** True when a segment switches between lower, upper and digit at least every other character. */
function isRandomSegment(segment: string): boolean {
  if (segment.length < HASH_MIN_SEGMENT) return false;
  let switches = 0;
  for (let i = 1; i < segment.length; i += 1) {
    if (charClass(segment.charAt(i)) !== charClass(segment.charAt(i - 1))) switches += 1;
  }
  return switches / segment.length >= HASH_SWITCH_RATIO;
}

/**
 * True for class names that look generated by a build tool (CSS modules, CSS-in-JS, minifiers).
 * They change on the site's next deploy, so candidates built on them are penalised, not refused.
 */
export function isHashedLike(token: string): boolean {
  if (GENERATED_PREFIX.test(token)) return true;
  return token.split(/[-_]+/).some(isRandomSegment);
}
